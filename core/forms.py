class ReportForm(forms.ModelForm):
    class Meta:
        model = InfrastructureReport
        fields = ['title', 'category', 'severity', 'barangay', 'description', 'photo']
        widgets = {
            'title': forms.TextInput(attrs={'class': 'w-full bg-[#FAF8F5] border border-[#E5E0D8] rounded-xl px-4 py-2 text-xs text-slate-900 outline-none focus:border-[#D97706]', 'placeholder': 'e.g., Deep pothole near school crossing'}),
            'category': forms.Select(attrs={'class': 'w-full bg-[#FAF8F5] border border-[#E5E0D8] rounded-xl px-4 py-2 text-xs text-slate-900 outline-none focus:border-[#D97706]'}),
            'severity': forms.Select(attrs={'class': 'w-full bg-[#FAF8F5] border border-[#E5E0D8] rounded-xl px-4 py-2 text-xs text-slate-900 outline-none focus:border-[#D97706]'}),
            'barangay': forms.Select(choices=BARANGAY_CHOICES, attrs={'class': 'w-full bg-[#FAF8F5] border border-[#E5E0D8] rounded-xl px-4 py-2 text-xs text-slate-900 outline-none focus:border-[#D97706]'}),
            'description': forms.Textarea(attrs={'class': 'w-full bg-[#FAF8F5] border border-[#E5E0D8] rounded-xl px-4 py-2 text-xs text-slate-900 outline-none focus:border-[#D97706]', 'rows': 3}),
            'photo': forms.FileInput(attrs={
                'class': 'w-full text-xs text-slate-600 file:mr-4 file:py-2 file:px-4 file:rounded-xl file:border-0 file:text-xs file:font-bold file:bg-[#1C2536] file:text-white hover:file:bg-[#2D3748] cursor-pointer',
                'id': 'id_image',
                'accept': 'image/*'
            }),
        }

